function isLanguageCode(value: string | null): value is LanguageCode {
  return LANGUAGES.some((language) => language.code === value)
}

function detectInitialLanguage(): LanguageCode {
  const storedLanguage = localStorage.getItem(LANGUAGE_STORAGE_KEY)
  if (isLanguageCode(storedLanguage)) return storedLanguage

  const browserLanguage = navigator.language.toLowerCase().split('-')[0]
  if (isLanguageCode(browserLanguage)) return browserLanguage

  return DEFAULT_LANGUAGE
}

function interpolate(template: string, params: TranslationParams = {}) {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? ''))
}

export function getItemPluralSuffix(language: LanguageCode, count: number) {
  if (count === 1 || language === 'eu') return ''
  if (language === 'de') return 'e'
  return 's'
}

const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<LanguageCode>(() => detectInitialLanguage())

  const activeLanguage = LANGUAGES.find((option) => option.code === language) ?? LANGUAGES[0]!

  const setLanguage = (nextLanguage: LanguageCode) => {
    setLanguageState(nextLanguage)
    localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage)
  }

  useEffect(() => {
    document.documentElement.lang = language
    document.title = TRANSLATIONS[language].appTitle ?? TRANSLATIONS.es.appTitle
  }, [language])

  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      locale: activeLanguage.locale,
      setLanguage,
      t: (key, params) => {
        const template = TRANSLATIONS[language][key] ?? TRANSLATIONS.es[key] ?? key
        return interpolate(template, params)
      },
    }),
    [activeLanguage.locale, language],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) {
    throw new Error('useI18n must be used within I18nProvider')
  }
  return context
}
